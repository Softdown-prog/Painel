import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { IncomingMessage, ServerResponse } from 'node:http';
import { AppError, dockerRequest, inspectOwned, validSlug, type DockerRequest } from './apps.ts';

export type DomainRoute = { slug: string; host: string; port: number; createdAt: string };
type Dependencies = {
  dataDir: string;
  send: (res: ServerResponse, status: number, value: unknown) => void;
  body: (req: IncomingMessage) => Promise<Record<string, unknown>>;
  docker?: DockerRequest;
  enabled?: boolean;
  zone?: string;
};
const NETWORK = 'softload_panel_apps';
const MAX_ROUTES = 8;
const RESERVED = new Set(['admin', 'api', 'app', 'auth', 'caddy', 'gateway', 'login', 'panel', 'portainer', 'www']);
const PORT_MIN = 1024;
class DomainError extends Error {
  readonly status: number;
  constructor(status: number, message: string) { super(message); this.status = status; }
}
export function validDomainZone(value: unknown): value is string {
  if (typeof value !== 'string' || value.length > 180) return false;
  // Only a dedicated first-level zone managed by this operator, e.g. apps.analysepro.com.
  return /^apps\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.[a-z]{2,}(?:\.[a-z]{2,})?$/.test(value) &&
    !value.includes('..');
}
function recordFile(dataDir: string): string {
  return join(dataDir, 'domain-routes.json');
}
export function readDomainRoutes(dataDir: string): DomainRoute[] {
  const path = recordFile(dataDir);
  if (!existsSync(path)) return [];
  const value: unknown = JSON.parse(readFileSync(path, 'utf8'));
  if (!Array.isArray(value) || value.length > MAX_ROUTES || !value.every((item: unknown) => {
    const route = item as DomainRoute;
    return item !== null && typeof item === 'object' && validSlug(route.slug) &&
      !RESERVED.has(route.slug) && typeof route.host === 'string' &&
      route.host === route.host.toLowerCase() && /^([a-z0-9-]+\.)+[a-z]{2,}$/.test(route.host) &&
      Number.isSafeInteger(route.port) && route.port >= PORT_MIN && route.port <= 65535 &&
      typeof route.createdAt === 'string';
  })) throw new DomainError(500, 'Registro de domínios inválido.');
  return value as DomainRoute[];
}
export function renderManagedCaddy(routes: readonly DomainRoute[]): string {
  const lines = ['# Generated by Softload Panel. Do not edit by hand.', '# Caddy gateway listens only on internal Docker networks.'];
  for (const route of [...routes].sort((a, b) => a.slug.localeCompare(b.slug))) {
    if (!validSlug(route.slug) || RESERVED.has(route.slug) ||
      !validDomainZone(route.host.slice(route.slug.length + 1)) ||
      !route.host.startsWith(route.slug + '.') ||
      !Number.isSafeInteger(route.port) || route.port < PORT_MIN || route.port > 65535)
      throw new DomainError(500, 'Tentativa de gerar rota Caddy inválida.');
    const matcher = route.slug.replaceAll('-', '_');
    lines.push('@panel_' + matcher + ' host ' + route.host);
    lines.push('handle @panel_' + matcher + ' {');
    lines.push('    reverse_proxy ' + 'softload-app-' + route.slug + ':' + route.port);
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}
function saveDomainRoutes(dataDir: string, routes: DomainRoute[]): void {
  mkdirSync(dataDir, { recursive: true, mode: 0o700 });
  const folder = join(dataDir, 'caddy');
  mkdirSync(folder, { recursive: true, mode: 0o755 });
  const file = recordFile(dataDir);
  const snippet = join(folder, 'managed-apps.caddy');
  const jsonTemp = file + '.' + process.pid + '.tmp';
  const caddyTemp = snippet + '.' + process.pid + '.tmp';
  const rendered = renderManagedCaddy(routes);
  writeFileSync(jsonTemp, JSON.stringify(routes, null, 2) + '\n', { mode: 0o600 });
  writeFileSync(caddyTemp, rendered, { mode: 0o644 });
  renameSync(caddyTemp, snippet);
  renameSync(jsonTemp, file);
}
let updateQueue: Promise<void> = Promise.resolve();
async function serialize<T>(callback: () => Promise<T>): Promise<T> {
  const previous = updateQueue;
  let release!: () => void;
  updateQueue = new Promise(resolve => { release = resolve; });
  await previous;
  try { return await callback(); } finally { release(); }
}
export async function handleDomainRoute(req: IncomingMessage, res: ServerResponse, deps: Dependencies): Promise<boolean> {
  const pathname = new URL(req.url || '/', 'http://panel.local').pathname;
  if (pathname !== '/domains' && pathname !== '/domains/caddy' &&
      !/^\/domains\/[a-z0-9-]+$/.test(pathname)) return false;
  const send = (status: number, value: unknown) => deps.send(res, status, value);
  const enabled = deps.enabled ?? process.env.PANEL_DOMAINS_ENABLED === '1';
  const zone = deps.zone ?? process.env.PANEL_APPS_DOMAIN_ZONE ?? '';
  const docker = deps.docker || dockerRequest;
  try {
    if (pathname === '/domains' && req.method === 'GET') {
      send(200, { enabled: enabled && validDomainZone(zone), zone: validDomainZone(zone) ? zone : null,
        network: NETWORK, activation: 'manual_caddy_reload', routes: readDomainRoutes(deps.dataDir) });
      return true;
    }
    if (pathname === '/domains/caddy' && req.method === 'GET') {
      send(200, { content: renderManagedCaddy(readDomainRoutes(deps.dataDir)), activation: 'manual_caddy_reload' });
      return true;
    }
    if (!enabled || !validDomainZone(zone))
      throw new DomainError(403, 'Domínios desabilitados ou zona apps. não configurada.');
    if (pathname === '/domains' && req.method === 'POST') {
      const input = await deps.body(req);
      if (Object.keys(input).sort().join(',') !== 'port,slug' || !validSlug(input.slug) ||
          RESERVED.has(input.slug) || !Number.isSafeInteger(input.port) ||
          (input.port as number) < PORT_MIN || (input.port as number) > 65535)
        throw new DomainError(400, 'Informe somente uma aplicação válida e porta interna de 1024 a 65535.');
      const details = await inspectOwned(docker, input.slug);
      if (details.HostConfig?.NetworkMode !== NETWORK)
        throw new DomainError(409, 'A aplicação deve ter sido criada na rede isolada softload_panel_apps.');
      const host = input.slug + '.' + zone;
      const route = await serialize(async () => {
        const routes = readDomainRoutes(deps.dataDir);
        if (routes.some(existing => existing.slug === input.slug || existing.host === host))
          throw new DomainError(409, 'Aplicação já possui domínio cadastrado.');
        if (routes.length >= MAX_ROUTES) throw new DomainError(409, 'Limite de oito domínios atingido.');
        const added: DomainRoute = { slug: input.slug as string, host,
          port: input.port as number, createdAt: new Date().toISOString() };
        saveDomainRoutes(deps.dataDir, [...routes, added]);
        return added;
      });
      console.log('Panel domain route staged:', route.slug, route.host, route.port);
      send(201, { route, requiresCaddyReload: true, live: false });
      return true;
    }
    const match = /^\/domains\/([a-z0-9-]+)$/.exec(pathname);
    if (match && req.method === 'DELETE') {
      if (!validSlug(match[1])) throw new DomainError(404, 'Domínio não encontrado.');
      await serialize(async () => {
        const routes = readDomainRoutes(deps.dataDir);
        if (!routes.some(route => route.slug === match[1])) throw new DomainError(404, 'Domínio não encontrado.');
        saveDomainRoutes(deps.dataDir, routes.filter(route => route.slug !== match[1]));
      });
      console.log('Panel domain route removed:', match[1]);
      send(200, { ok: true, requiresCaddyReload: true, live: false });
      return true;
    }
    throw new DomainError(405, 'Método não permitido.');
  } catch (error) {
    if (error instanceof DomainError || error instanceof AppError)
      send(error.status, { error: error.message });
    else if (error instanceof SyntaxError) send(400, { error: 'JSON inválido.' });
    else {
      console.error('Panel domain error:', error instanceof Error ? error.message : String(error));
      send(502, { error: 'Não foi possível registrar o domínio.' });
    }
    return true;
  }
}
