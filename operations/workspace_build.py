def toolbox_profile(profile: str) -> bool:
    return profile in ('lhs-toolbox-precommit', 'terrania-toolbox-precommit')


def terrania_profile(profile: str) -> bool:
    return profile in ('terrania-core', 'terrania-precommit', 'terrania-toolbox-precommit')


def project_dir(name: str, root: Path = WORKSPACES) -> Path:
    if not isinstance(name, str) or not PROJECT_RE.fullmatch(name):
        raise ValueError('Projeto inválido')
    if root.is_symlink():
        raise ValueError('Raiz de workspaces não confiável')
    path = root / name
    if not path.is_dir() or path.is_symlink():
        raise ValueError('Workspace indisponível ou simbólico')
    return path


def docker_args(work: Path, *, source: Path | None, phase: str, network='none', container_name: str | None = None, video: bool = False, terrania: bool = False, toolbox: bool = False) -> list[str]:
    # No ports, Docker socket, host filesystem root, privileged mode or extra capabilities.
    if network not in ('none', 'bridge'):
        raise ValueError('Rede não autorizada')
    if container_name is not None and not re.fullmatch(r'panel-ws-[a-f0-9]{16}-[0-9]{1,2}', container_name):
        raise ValueError('Nome de container inválido')
    argv = ['docker', 'run', '--rm', '--pull=never', '--init', '--read-only', '--cap-drop=ALL',
            '--security-opt=no-new-privileges:true', '--pids-limit=128',
            # IPC /dev/shm sizing is not a limit on total container RAM.
            '--shm-size='+('384m' if video else '256m'),
            '--network='+network, '--user=61110:61110',
            '--tmpfs=/tmp:rw,nosuid,nodev,size=128m',
            '--env=HOME=/work/.home', '--env=npm_config_cache=/work/.npm-cache',
            *(('--name='+container_name,) if container_name else ()),
            '--mount=type=bind,src='+str(work)+',dst=/work',
            '--workdir='+('/work' if source is not None or terrania else '/work/games/lan_house_simulator')]
    if source is not None:
        argv += ['--mount=type=bind,src='+str(source)+',dst=/source,readonly']
    argv += [TOOLBOX_IMAGE if toolbox else IMAGE, 'sh', '-eu', '-c', phase]
    return argv


def clean_copy_command(profile: str = 'lhs-precommit') -> str:
    # The source is mounted only with --network=none. Dependency installs and
    # tests see the *sanitized copy*, never the private project mount.
    if terrania_profile(profile):
        source_check = ("test -f /source/package.json; test -f /source/angular.json; "
                        "grep -Eq '\"name\"[[:space:]]*:[[:space:]]*\"terrania-origins\"' /source/package.json; ")
    else:
        source_check = "test -f /source/games/lan_house_simulator/package.json; "
    return (source_check +
            "cp -R /source/. /work/; "
            "find /work -type d \\( -name .git -o -name node_modules -o -name .codex \\) -prune -exec rm -rf {} +; "
            "find /work -type f \\( -name .env -o -name '.env.*' -o -name .npmrc -o -name auth.json \\) ! -name .env.example -delete; "
            # Preserve tracked .env.example paths for the architecture index,
            # but blank their contents so examples never carry sample secrets.
            "find /work -type f -name .env.example -exec sh -c 'for file do : > \"$file\"; done' sh {} +; "
            "mkdir -p /work/.home /work/.npm-cache" +
            ("; if test -f /source/.env.example; then : > /work/.env.example; fi"
             if terrania_profile(profile) else ""))


def write_state(job: Path, **values: object) -> None:
    path = job / 'status.json'
    previous = json.loads(path.read_text()) if path.exists() else {}
    previous.update(values)
    temp = job / 'status.tmp'
    temp.write_text(json.dumps(previous, sort_keys=True))
    os.replace(temp, path)


def collect_visual_artifacts(work: Path, folder: Path, *, terrania: bool = False) -> list[str]:
    """Preserve only bounded real browser images and clips; never the source tree."""
    output = (work / 'test-results') if terrania else (work / 'games' / 'lan_house_simulator' / 'out' / 'validation')
    if not output.is_dir() or output.is_symlink():
        return []
    destination = folder / 'artifacts'
    max_files, max_bytes, max_file = 100, 48*1024*1024, 12*1024*1024
    total = 0
    retained = []
    for candidate in sorted(output.rglob('*')):
        if len(retained) >= max_files:
            break
        if candidate.is_symlink() or not candidate.is_file():
            continue
        if candidate.suffix.lower() not in ('.png', '.webp', '.webm'):
            continue
        if not re.fullmatch(r'[A-Za-z0-9._-]{1,95}', candidate.name):
            continue
        if not candidate.resolve().is_relative_to(output.resolve()):
            continue
        size = candidate.stat().st_size
        if size < 32 or size > max_file or total + size > max_bytes:
            continue
        destination.mkdir(mode=0o700, exist_ok=True)
        safe_name = f'{len(retained):03d}-{candidate.name}'
        target = destination / safe_name
        with candidate.open('rb') as src, target.open('xb') as dst:
            shutil.copyfileobj(src, dst)
        target.chmod(0o600)
        retained.append(safe_name)
        total += size
    return retained


def run_pipeline(job_id: str, root: Path = WORKSPACES, jobs: Path = JOBS) -> None:
    folder = jobs / job_id
    state = json.loads((folder / 'status.json').read_text())
    try:
        source = project_dir(state['project'], root)
        profile = state['profile']
        if profile not in PROFILES:
            raise ValueError('Perfil desconhecido')
    except (ValueError, KeyError) as exc:
        write_state(folder, status='failed', success=False, error=str(exc)[:400], finished=time.time())
        return
    lock_path = jobs / '.active.lock'
    lock_path.touch(exist_ok=True)
    with lock_path.open('r+') as lock:
        try:
            # Readers may build concurrently. Installer and GC take the exclusive
            # form of this same lock to prevent replacement or cleanup mid-build.
            fcntl.flock(lock, fcntl.LOCK_SH | fcntl.LOCK_NB)
        except BlockingIOError:
            write_state(folder, status='busy', finished=time.time(), success=False)
            return
        work = folder / 'source'
        work.mkdir(mode=0o700)
        # The trusted supervisor must create the writable bind mount for the
        # unprivileged Docker user; root credentials are never mounted.
        os.chown(work, 61110, 61110)
        write_state(folder, status='running', started=time.time(), current='snapshot')
        steps = [('snapshot', clean_copy_command(profile), 120, 'none', source),
                 *[(name, command, timeout, network, None)
                   for name, command, timeout, network in PROFILES[profile]]]
        try:
            for index, (name, command, limit, network, snapshot_source) in enumerate(steps):
                write_state(folder, current=name)
                print('=== '+name+' ===', flush=True)
                video = name in ('ps1-integrated', 'ps2-integrated', 'terrania-browser-desktop', 'terrania-browser-android')
                container = f'panel-ws-{job_id}-{index}'
                argv = docker_args(work, source=snapshot_source, phase=command,
                                   network=network, container_name=container, video=video,
                                   terrania=terrania_profile(profile), toolbox=toolbox_profile(profile))
                try:
                    result = subprocess.run(argv, stdin=subprocess.DEVNULL, timeout=limit, check=False)
                    if result.returncode != 0:
                        raise RuntimeError(f'{name}: código de saída {result.returncode}')
                except subprocess.TimeoutExpired as exc:
                    # Killing the Docker CLI does not guarantee the container stops.
                    # Target only the deterministic disposable container of this job.
                    subprocess.run(['docker', 'rm', '-f', container], timeout=30,
                                   stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                   stderr=subprocess.DEVNULL, check=False)
                    raise RuntimeError(f'{name}: excedeu {limit} segundos') from exc
            write_state(folder, status='passed', current=None, success=True, finished=time.time())
            print('RESULTADO: APROVADO', flush=True)
        except Exception as exc:
            write_state(folder, status='failed', current=name, success=False, error=str(exc)[:400], finished=time.time())
            print('RESULTADO: FALHOU - '+str(exc)[:400], flush=True)
        finally:
            try:
                retained = collect_visual_artifacts(work, folder, terrania=terrania_profile(profile))
                write_state(folder, artifacts=retained)
            except Exception:
                # Saving optional review images must never turn failed tests green.
                write_state(folder, artifacts=[], artifactError='Não foi possível preservar imagens.')
            shutil.rmtree(work, ignore_errors=True)


def start(project: str, profile: str = 'lhs-precommit', root: Path = WORKSPACES, jobs: Path = JOBS) -> str:
    project_dir(project, root)
    if profile not in PROFILES:
        raise ValueError('Perfil inválido')
    if os.geteuid() != 0:
        raise PermissionError('Execute somente pelo broker administrativo autorizado da VPS')
    jobs.mkdir(parents=True, exist_ok=True)
    job_id = secrets.token_hex(8)
    folder = jobs / job_id
    folder.mkdir(mode=0o700)
    write_state(folder, status='queued', success=None, project=project, profile=profile, created=time.time())
    output = (folder / 'output.log').open('wb')
    try:
        worker_argv = [sys.executable, str(Path(__file__).resolve()), '_worker', job_id]
        if root == CHATGPT_WORKSPACES:
            worker_argv.append('chatgpt')
        worker = subprocess.Popen(worker_argv,
                                  stdin=subprocess.DEVNULL, stdout=output, stderr=subprocess.STDOUT,
                                  close_fds=True, start_new_session=True)
        write_state(folder, pid=worker.pid)
    except Exception as exc:
        write_state(folder, status='failed', success=False, error='Não foi possível iniciar o supervisor')
        raise RuntimeError('Falha ao iniciar supervisor do workspace') from exc
    finally:
        output.close()
    return job_id


def redact(text: str) -> str:
    text = re.sub(r'\b(?:gh[pousr]_|github_pat_|sk-proj-|APP_USR-|cfat_)[A-Za-z0-9_\/-]{10,}', '[TOKEN OCULTO]', text)
    return re.sub(r'((?:password|secret|authorization|api[_-]?key|access[_-]?token)\s*[:=]\s*)[^\r\n]+',
                  r'\1[OCULTO]', text, flags=re.IGNORECASE)

def status(job_id: str, jobs: Path = JOBS) -> dict:
    if not JOB_RE.fullmatch(job_id):
        raise ValueError('Identificador inválido')
    folder = jobs / job_id
    if not folder.is_dir() or folder.is_symlink():
        raise ValueError('Job não encontrado')
    state = json.loads((folder / 'status.json').read_text())
    log = folder / 'output.log'
    if log.exists():
        with log.open('rb') as source:
            source.seek(max(0, source.seek(0, 2) - 5000))
            tail = source.read().decode('utf8', 'replace')
        # Return only a bounded log excerpt; never print raw workspace files.
        state['logTail'] = redact(tail[-4000:])
    return {k: v for k, v in state.items() if k != 'pid'}


def collect_expired_jobs(jobs: Path = JOBS, *, days: int = 7,
                         dry_run: bool = True, now: float | None = None) -> dict:
    """Remove only old, completed direct-child jobs with the worker lock held.

    Queued/running jobs and unknown/symlink entries are never touched.
    """
    if not isinstance(days, int) or not 1 <= days <= 30:
        raise ValueError('Retenção inválida: 1 a 30 dias')
    if jobs.is_symlink() or not jobs.is_dir():
        raise ValueError('Raiz de jobs indisponível ou simbólica')
    current = time.time() if now is None else now
    cutoff = current - days * 86400
    lock_path = jobs / '.active.lock'
    if lock_path.is_symlink():
        raise ValueError('Lock de jobs inseguro')
    lock_path.touch(exist_ok=True)
    with lock_path.open('r+') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise RuntimeError('Build em andamento: limpeza recusada')
        expired = []
        kept = 0
        for entry in jobs.iterdir():
            if not JOB_RE.fullmatch(entry.name) or entry.is_symlink() or not entry.is_dir():
                continue
            state_file = entry / 'status.json'
            if not state_file.is_file() or state_file.is_symlink():
                kept += 1
                continue
            try:
                state = json.loads(state_file.read_text())
            except (ValueError, OSError):
                kept += 1
                continue
            if state.get('status') not in ('passed', 'failed', 'busy'):
                kept += 1
                continue
            finished = state.get('finished')
            if isinstance(finished, bool) or not isinstance(finished, (int, float)):
                kept += 1
                continue
            if not 0 < finished < cutoff:
                kept += 1
                continue
            expired.append(entry.name)
            if not dry_run:
                shutil.rmtree(entry)
        return {'dryRun': dry_run, 'retentionDays': days,
                'eligible': sorted(expired), 'kept': kept}


def main() -> int:
    parser = argparse.ArgumentParser(description='Workspace de build isolado; somente perfis fixos')
    sub = parser.add_subparsers(dest='action', required=True)
    begin = sub.add_parser('start');begin.add_argument('project');begin.add_argument('profile', nargs='?', default='lhs-precommit', choices=PROFILES)
    check = sub.add_parser('status');check.add_argument('job_id')
    cleanup = sub.add_parser('gc');cleanup.add_argument('--days',type=int,default=7);cleanup.add_argument('--apply',action='store_true')
    worker = sub.add_parser('_worker', help=argparse.SUPPRESS);worker.add_argument('job_id');worker.add_argument('scope',nargs='?',choices=['codex','chatgpt'],default='codex')
    args = parser.parse_args()
    try:
        if args.action == 'start':
            print(json.dumps({'jobId': start(args.project, args.profile), 'status':'queued'}))
        elif args.action == 'status':
            print(json.dumps(status(args.job_id)))
        elif args.action == 'gc':
            if os.geteuid() != 0:
                raise PermissionError('Limpeza permitida apenas ao administrador')
            print(json.dumps(collect_expired_jobs(days=args.days, dry_run=not args.apply)))
        else:
            if not JOB_RE.fullmatch(args.job_id):
                raise ValueError('Job inválido')
            run_pipeline(args.job_id, CHATGPT_WORKSPACES if args.scope == 'chatgpt' else WORKSPACES)
    except Exception as exc:
        print(json.dumps({'error':str(exc)[:300]}), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
